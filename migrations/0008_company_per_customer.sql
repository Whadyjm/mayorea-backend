-- One profile for the distributor (customer_id is null) and one per commerce
-- (customer_id = its customer). Until now the table held only the distributor, as id 1.
alter table company drop constraint company_id_check;
alter table company drop constraint company_pkey;
alter table company alter column id type bigint;
alter table company alter column id add generated by default as identity (start with 1000);
alter table company add primary key (id);
alter table company add column customer_id bigint references customers (id) on delete cascade;

create unique index company_one_per_customer on company (customer_id) where customer_id is not null;
create unique index company_one_distributor on company ((customer_id is null)) where customer_id is null;
